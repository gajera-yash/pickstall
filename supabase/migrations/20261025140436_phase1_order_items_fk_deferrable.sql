-- Fix: deleting a user who owns a store with sales failed ("Database error deleting user").
--
-- Deleting the auth user cascades profiles -> stores -> (products, orders). Postgres checks the
-- order_items -> products NO ACTION constraint as soon as the products cascade finishes, before
-- the orders -> order_items cascade has run, so the order_items rows still exist and the delete
-- is rejected. Making the constraint deferrable moves the check to commit time, when the
-- cascade has removed those order_items.
--
-- Unchanged on purpose: deleting a single product that has sales still fails at commit
-- (order_items still reference it), so sales history is kept. Creators archive such products.
-- Do not edit this file once pushed.

alter table public.order_items
  drop constraint order_items_product_id_fkey;

alter table public.order_items
  add constraint order_items_product_id_fkey
  foreign key (product_id) references public.products (id)
  deferrable initially deferred;
