-- Phase 1 Row Level Security: PRD.md section 5.5 with the fixes in docs/DECISIONS.md D-004.
--
-- Two layers protect every table:
--   1. Grants decide WHICH COLUMNS a role may touch (e.g. nobody but the service role can
--      write stores.stripe_charges_enabled or profiles.role).
--   2. RLS policies decide WHICH ROWS a role may touch (ownership / self).
-- The service role bypasses RLS and keeps its default grants; it is used only by server code.
--
-- Rule for every future table: enable RLS, revoke all from anon and authenticated,
-- then grant only what is needed and add explicit policies. Do not edit this file once pushed.

-- ---------------------------------------------------------------------------
-- Ownership helper
-- ---------------------------------------------------------------------------

-- security definer so policies on other tables can check ownership without recursing
-- through stores RLS. search_path is pinned so the function cannot be hijacked.
create or replace function public.owns_store(p_store_id uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.stores s
    where s.id = p_store_id
      and s.owner_id = (select auth.uid())
  );
$$;

revoke all on function public.owns_store(uuid) from public, anon, authenticated;
grant execute on function public.owns_store(uuid) to authenticated;

revoke all on function public.set_updated_at() from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Enable RLS everywhere
-- ---------------------------------------------------------------------------

alter table public.profiles enable row level security;
alter table public.stores enable row level security;
alter table public.products enable row level security;
alter table public.product_files enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.enrollments enable row level security;
alter table public.webhook_events enable row level security;
alter table public.email_log enable row level security;

-- ---------------------------------------------------------------------------
-- Grants: start from nothing for client roles, then add back the minimum
-- ---------------------------------------------------------------------------

revoke all on table
  public.profiles,
  public.stores,
  public.products,
  public.product_files,
  public.orders,
  public.order_items,
  public.enrollments,
  public.webhook_events,
  public.email_log
from anon, authenticated;

-- profiles: read own row, change only the display name. role/email are server-managed.
grant select on public.profiles to authenticated;
grant update (full_name) on public.profiles to authenticated;

-- stores: owner creates and edits store settings. Stripe fields, custom_domain and
-- owner_id changes are service-role only. No client delete in Phase 1.
grant select on public.stores to authenticated;
grant insert (owner_id, slug, name, bio, avatar_url, theme, social_links, currency)
  on public.stores to authenticated;
grant update (slug, name, bio, avatar_url, theme, social_links, currency, is_published)
  on public.stores to authenticated;

-- products and their files: full CRUD for the store owner (rows limited by RLS below).
grant select, insert, update, delete on public.products to authenticated;
grant select, insert, update, delete on public.product_files to authenticated;

-- Sales data is written only by the verified webhook (service role). Clients read only.
grant select on public.orders to authenticated;
grant select on public.order_items to authenticated;
grant select on public.enrollments to authenticated;

-- webhook_events and email_log: no client grants and no policies on purpose.
-- Only the service role (which bypasses RLS) may read or write them.
comment on table public.webhook_events is
  'Service role only. RLS enabled with no policies and no client grants on purpose.';
comment on table public.email_log is
  'Service role only. RLS enabled with no policies and no client grants on purpose.';

-- ---------------------------------------------------------------------------
-- Policies
-- ---------------------------------------------------------------------------

-- profiles
create policy "profiles: read own"
  on public.profiles for select to authenticated
  using (id = (select auth.uid()));

create policy "profiles: update own"
  on public.profiles for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

-- stores
create policy "stores: owner reads"
  on public.stores for select to authenticated
  using (owner_id = (select auth.uid()));

create policy "stores: owner creates own"
  on public.stores for insert to authenticated
  with check (owner_id = (select auth.uid()));

create policy "stores: owner updates"
  on public.stores for update to authenticated
  using (owner_id = (select auth.uid()))
  with check (owner_id = (select auth.uid()));

-- products
create policy "products: owner reads"
  on public.products for select to authenticated
  using (public.owns_store(store_id));

create policy "products: owner creates"
  on public.products for insert to authenticated
  with check (public.owns_store(store_id));

create policy "products: owner updates"
  on public.products for update to authenticated
  using (public.owns_store(store_id))
  with check (public.owns_store(store_id));

create policy "products: owner deletes"
  on public.products for delete to authenticated
  using (public.owns_store(store_id));

-- product_files (no store_id column: ownership goes through the product)
create policy "product_files: owner reads"
  on public.product_files for select to authenticated
  using (exists (
    select 1 from public.products p
    where p.id = product_files.product_id and public.owns_store(p.store_id)
  ));

create policy "product_files: owner creates"
  on public.product_files for insert to authenticated
  with check (exists (
    select 1 from public.products p
    where p.id = product_files.product_id and public.owns_store(p.store_id)
  ));

create policy "product_files: owner updates"
  on public.product_files for update to authenticated
  using (exists (
    select 1 from public.products p
    where p.id = product_files.product_id and public.owns_store(p.store_id)
  ))
  with check (exists (
    select 1 from public.products p
    where p.id = product_files.product_id and public.owns_store(p.store_id)
  ));

create policy "product_files: owner deletes"
  on public.product_files for delete to authenticated
  using (exists (
    select 1 from public.products p
    where p.id = product_files.product_id and public.owns_store(p.store_id)
  ));

-- orders: the store owner and the buyer can read; nobody writes from the client.
create policy "orders: store owner or buyer reads"
  on public.orders for select to authenticated
  using (public.owns_store(store_id) or buyer_user_id = (select auth.uid()));

-- order_items: same readers as the parent order.
create policy "order_items: store owner or buyer reads"
  on public.order_items for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.id = order_items.order_id
      and (public.owns_store(o.store_id) or o.buyer_user_id = (select auth.uid()))
  ));

-- enrollments: the buyer reads own; the creator reads enrollments of their products.
create policy "enrollments: buyer or product owner reads"
  on public.enrollments for select to authenticated
  using (
    user_id = (select auth.uid())
    or exists (
      select 1 from public.products p
      where p.id = enrollments.product_id and public.owns_store(p.store_id)
    )
  );

-- ---------------------------------------------------------------------------
-- Public views (storefront reads for anon and signed-in visitors)
-- ---------------------------------------------------------------------------
-- These views run with the view owner's rights (security_invoker = false), which is the
-- only way to expose a safe subset of columns while the base tables stay closed to anon.
-- Supabase's linter flags this as "security definer view": that is intended here.
-- security_barrier stops user-supplied filters from being evaluated before the WHERE
-- clause. Clients get SELECT only: simple views are auto-updatable, so no other grant
-- may ever be added to them.

create view public.public_stores
with (security_invoker = false, security_barrier = true)
as
select
  s.id,
  s.slug,
  s.name,
  s.bio,
  s.avatar_url,
  s.theme,
  s.social_links,
  s.currency,
  s.stripe_charges_enabled as can_accept_payments
from public.stores s
where s.is_published;

create view public.public_products
with (security_invoker = false, security_barrier = true)
as
select
  p.id,
  p.store_id,
  p.type,
  p.title,
  p.slug,
  p.description,
  p.cover_url,
  p.price_cents,
  p.compare_at_price_cents,
  p.pricing_model,
  p.min_price_cents,
  p.sort_order
from public.products p
where p.status = 'published'
  and exists (
    select 1 from public.stores s
    where s.id = p.store_id and s.is_published
  );

revoke all on public.public_stores, public.public_products from public, anon, authenticated;
grant select on public.public_stores, public.public_products to anon, authenticated;
